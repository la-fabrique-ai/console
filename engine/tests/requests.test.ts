import assert from "node:assert/strict";
import { readFileSync, unlinkSync, writeFileSync } from "node:fs";
import { test } from "node:test";
import { development } from "./develop-project.ts";

test("a request remembers the terminal that asked; concurrent answers use the first text once", async t => {
  const p = development(t);
  await p.action("develop.start"); const lead = p.state().agents.lead;
  await p.action("lead.build",{ ticketId: "1" },lead.id);
  const dev = p.state().agents.dev, question = { text: "Quelle présentation souhaitez-vous ?", context: "Choix du projet.", choices: ["Liste"] };
  assert.ok((await p.action("request.ask", { ...question, ticketId: "2" },dev.id)).error);
  assert.ok((await p.action("request.ask", { ...question, issueKey: "DEMO-2" },dev.id)).error);
  assert.ok((await p.action("request.ask",question)).error);
  const asked = await p.action("request.ask", { ...question, from: "reviewer" },dev.id);
  const request = asked.data?.development.requests[0];
  assert.equal(request?.from,"dev",JSON.stringify(asked)); assert.equal(request.ticketId,"1");
  const answer = { requestId: request.id, text: "La liste.\n" + "Détail. ".repeat(600) };
  assert.ok((await p.action("requests.answer",answer,dev.id)).error);
  const [a,b] = await Promise.all([p.action("requests.answer",answer),p.action("requests.answer",answer)]);
  assert.deepEqual(a,b); assert.equal(a.data.development.requests[0].answer,answer.text);
  assert.deepEqual(await p.action("requests.answer",{ ...answer, text: "Autre." }),a);
  const sends = () => p.calls().filter(c => c[0] === "send");
  assert.equal(sends().length,1); assert.equal(sends()[0][2],dev.terminal); assert.equal(JSON.parse(sends()[0][3]).text,answer.text);
  const other = await p.action("request.ask",question,lead.id);
  const requestId = other.data.development.requests[1].id;
  writeFileSync(p.path("live"),JSON.stringify({ terminals: [] })); await p.action("develop.start");
  writeFileSync(p.path("offline"),"lost receipt");
  assert.ok((await p.action("requests.answer",{ requestId,text:"Oui" })).error);
  assert.equal((await p.action("missions.show")).data.development.requests[1].answer,undefined);
  unlinkSync(p.path("offline"));
  writeFileSync(p.path("lose-send"),"after receipt");
  assert.ok((await p.action("requests.answer",{ requestId,text:"Autre réponse" })).error);
  const confirmed = await p.action("requests.answer",{ requestId,text:"Oui" });
  assert.equal(confirmed.data.development.requests[1].answer,"Oui");
  assert.equal(sends().length,3); assert.equal(sends()[2][2],lead.terminal);
  const delivered = readFileSync(p.path("delivered"),"utf8").trim().split("\n").map(l => JSON.parse(l));
  assert.equal(delivered.length,2);
  assert.equal(JSON.parse(delivered[1][3]).text,"Oui");
});
